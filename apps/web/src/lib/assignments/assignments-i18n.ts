const DICTS: Record<string, Dict> = { en, ar };

/** Exported for the EN/AR key-parity test — the assignments surface ships bilingual. */
export const ASSIGNMENTS_DICTS: Readonly<Record<string, Dict>> = DICTS;

export type AssignmentsT = (key: string, vars?: Record<string, string | number> | string) => string;

export interface UseAssignmentsI18n {
  t: AssignmentsT;
  locale: string;
  dir: "ltr" | "rtl";
}

/** Assignments-scoped translator; reuses the app locale + direction. */
export function useAssignmentsI18n(): UseAssignmentsI18n {
  const { locale, dir } = useI18n();
  const dict = DICTS[locale] ?? en;
  const t: AssignmentsT = (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars && typeof vars === "object") {
      for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    }
    return s;
  };
  return { t, locale, dir };
}
